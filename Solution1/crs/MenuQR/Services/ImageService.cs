using System.Text.RegularExpressions;

namespace MenuQR.Api.Services;

public class ImageUploadException : Exception
{
    public ImageUploadException(string message) : base(message) { }
}

public interface IImageService
{
    Task<string> UploadAsync(IFormFile file, string folder);
    bool IsOurImageUrl(string? url);
}

public class ImageService : IImageService
{
    private const long MaxBytes = 5 * 1024 * 1024; // 5 MB

    private static readonly Regex UrlPattern =
        new(@"^/media/[a-z0-9\-]+/[a-f0-9]{32}\.(jpg|png|webp)$", RegexOptions.Compiled);

    private readonly string _mediaRoot;

    public ImageService(IWebHostEnvironment env)
    {
        var webRoot = env.WebRootPath ?? Path.Combine(env.ContentRootPath, "wwwroot");
        _mediaRoot = Path.Combine(webRoot, "media");
        Directory.CreateDirectory(_mediaRoot);
    }

    // Only accept empty values or paths that this service created itself
    public bool IsOurImageUrl(string? url)
    {
        if (string.IsNullOrWhiteSpace(url)) return true;
        return UrlPattern.IsMatch(url);
    }

    public async Task<string> UploadAsync(IFormFile file, string folder)
    {
        if (file.Length == 0)
            throw new ImageUploadException("The file is empty.");
        if (file.Length > MaxBytes)
            throw new ImageUploadException("The image is too large (max 5 MB).");

        var ext = await DetectExtensionAsync(file);
        if (ext is null)
            throw new ImageUploadException("Only JPG, PNG or WEBP images are allowed.");

        // The folder name is generated by our code, but we clean it anyway
        var safeFolder = Regex.Replace(folder.ToLowerInvariant(), "[^a-z0-9\\-]", "");
        if (safeFolder.Length == 0) safeFolder = "misc";

        var dir = Path.Combine(_mediaRoot, safeFolder);
        Directory.CreateDirectory(dir);

        var fileName = Guid.NewGuid().ToString("N") + ext;
        var fullPath = Path.Combine(dir, fileName);

        await using (var target = File.Create(fullPath))
        {
            await file.CopyToAsync(target);
        }

        return $"/media/{safeFolder}/{fileName}";
    }

    // Looks at the first bytes of the file: JPEG, PNG or WEBP
    private static async Task<string?> DetectExtensionAsync(IFormFile file)
    {
        var h = new byte[12];
        await using var s = file.OpenReadStream();
        var read = await s.ReadAtLeastAsync(h, 12, throwOnEndOfStream: false);
        if (read < 12) return null;

        if (h[0] == 0xFF && h[1] == 0xD8 && h[2] == 0xFF) return ".jpg";
        if (h[0] == 0x89 && h[1] == 0x50 && h[2] == 0x4E && h[3] == 0x47) return ".png";
        if (h[0] == 0x52 && h[1] == 0x49 && h[2] == 0x46 && h[3] == 0x46 &&
            h[8] == 0x57 && h[9] == 0x45 && h[10] == 0x42 && h[11] == 0x50) return ".webp";

        return null;
    }
}
